_DATA_DIR_TX = "/data" if __import__("os").path.isdir("/data") else "."
WELCOME_FILE = _DATA_DIR_TX + "/welcome_text.json"

def get_custom_welcome(lang="uz"):
    """Returns dict {text, photo, video} or None."""
    import json, os
    try:
        if os.path.exists(WELCOME_FILE):
            with open(WELCOME_FILE, 'r', encoding='utf-8') as f:
                data = json.load(f)
                raw = data.get(lang) or data.get("uz")
                if raw is None:
                    return None
                if isinstance(raw, str):
                    return {"text": raw, "photo": None, "video": None}
                return {"text": raw.get("text"), "photo": raw.get("photo"), "video": raw.get("video")}
    except:
        pass
    return None

def save_custom_welcome(text=None, lang="uz", photo=None, video=None):
    """Save welcome content. Pass only the fields you want to update."""
    import json, os
    try:
        data = {}
        if os.path.exists(WELCOME_FILE):
            with open(WELCOME_FILE, 'r', encoding='utf-8') as f:
                data = json.load(f)
        existing = data.get(lang)
        if isinstance(existing, str):
            existing = {"text": existing, "photo": None, "video": None}
        elif not isinstance(existing, dict):
            existing = {"text": None, "photo": None, "video": None}
        if text is not None:
            existing["text"] = text
        if photo is not None:
            existing["photo"] = photo
        if video is not None:
            existing["video"] = video
        data[lang] = existing
        os.makedirs(os.path.dirname(WELCOME_FILE), exist_ok=True)
        with open(WELCOME_FILE, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False)
        return True
    except:
        return False

def t(user_id, key, **kwargs):
    from data import get_lang
    lang = get_lang(user_id)
    if key == "welcome":
        custom = get_custom_welcome(lang)
        if custom and custom.get("text"):
            return custom["text"]
    text = TEXTS.get(lang, TEXTS["uz"]).get(key, "")
    if kwargs:
        text = text.format(**kwargs)
    return text


def get_welcome_media(user_id):
    """Returns (photo_file_id, video_file_id) for the custom welcome message, or (None, None)."""
    from data import get_lang
    lang = get_lang(user_id)
    custom = get_custom_welcome(lang)
    if custom:
        return custom.get("photo"), custom.get("video")
    return None, None
